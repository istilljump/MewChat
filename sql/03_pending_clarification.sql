-- 03 澄清挂起状态
--
-- 阶段 8 引入。澄清追问需要记住"上一轮问了什么、用户在哪些候选里挑"，
-- 否则用户在下一轮回复一个序号（"1"）时，无法还原成具体订单 ——
-- 拿"1"去做意图识别，模型只能给出 UNKNOWN。
--
-- 该状态与会话是严格的一对一、生命周期完全跟随会话（被回答或过期即清空），
-- 因此做成 conversation 的一列，而不是独立表：
-- 独立成表只会多一次 join，还要维护一张大多数行为空的表。
--
-- 执行顺序：在 01_schema.sql（01 建表）与 02_knowledge_chunk.sql 之后执行。
-- 注意：MySQL 不支持 ADD COLUMN IF NOT EXISTS，本脚本不可重复执行。
-- ============================================================

ALTER TABLE `conversation`
    ADD COLUMN `pending_clarification` JSON NULL
        COMMENT '挂起的澄清追问(JSON):原问题/意图/缺失参数/候选列表;无待澄清项时为NULL'
        AFTER `summary`;

-- 说明：不加索引。该列只按主键所在的会话行读取（会话查询走 uk_session_id），
-- 不存在"按挂起状态反查会话"的查询场景；给 JSON 列加索引也起不到过滤作用。
