-- =============================================================================
-- 07 消息级用户反馈（点赞 / 点踩）
--
-- 背景
--   对话页每条助手回答下面有 👍 / 👎，此前只有界面、点了提示"未接入后端"。
--   本脚本给 message 表加上承载它的两列。
--
-- 为什么用列而不是新表
--   反馈与消息严格一对一、生命周期完全跟随消息（消息删了反馈没有意义），
--   独立建表只多一次 join，换不来任何好处。
--
-- 语义
--   feedback      1 = 有用，2 = 无用，NULL = 未反馈（取值见 MessageService 的常量）
--   feedback_time 最后一次反馈的时间
--   **允许改主意**：后写覆盖先写，只保留最后一次选择与时间 ——
--   保留历史投票需要审计表，而这里要的是"用户最终怎么看这条回答"。
--
-- 影响范围
--   仅新增两个可空列，不动索引与既有数据。ADD COLUMN 不可重复执行
--   （MySQL 不支持 ADD COLUMN IF NOT EXISTS），升级时执行一次即可。
--   全新部署由本脚本统一建列，不必改 01_schema.sql。
--
-- 执行顺序
--   01 → 02 → 03 → 04 → 05 → 07
-- =============================================================================

ALTER TABLE `message`
    ADD COLUMN `feedback` TINYINT NULL COMMENT '用户反馈：1有用 2无用，NULL未反馈' AFTER `error_msg`,
    ADD COLUMN `feedback_time` DATETIME NULL COMMENT '最近一次反馈时间' AFTER `feedback`;
