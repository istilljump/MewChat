-- =============================================================================
-- 05 低置信度问题池：question 列宽与用户消息上限对齐
--
-- 背景
--   用户消息允许到 ChatConstants.MAX_MESSAGE_LENGTH = 2000 字，
--   而 low_confidence_question.question 建表时是 VARCHAR(1000)。
--   MySQL 8 默认严格模式下，长度 1001~2000 的问题写入直接报 1406，
--   写入方只能吞掉异常 —— 表现为"这个问题兜底了，但它在补知识的问题池里找不到"。
--   数据飞轮少一块最该被优化的问题（问得越长往往越复杂），且没有任何报错。
--
-- 影响范围
--   仅列宽。索引、唯一键、其它列都不变，可用本脚本在已有库上升级。
--   MODIFY COLUMN 可重复执行。全新部署直接执行 01_schema.sql 即可，
--   其中的建表语句已经改成 VARCHAR(2000)。
--
-- 执行顺序
--   01 → 02 → 03 → 04 → 05
-- =============================================================================

ALTER TABLE `low_confidence_question`
    MODIFY COLUMN `question` VARCHAR(2000) NOT NULL COMMENT '用户问题原文(取首次出现的写法)，列宽与 ChatConstants.MAX_MESSAGE_LENGTH 对齐';
